"""One conversation: history + system prompt + the router that picks the model."""
from __future__ import annotations

import datetime
from dataclasses import dataclass, field
from typing import Iterator

from . import AUTHOR, HOMEPAGE, soul
from .router import Router, Switched

MAX_HISTORY = 30          # messages kept in context (older ones are dropped)


def system_prompt(name: str = "", now: datetime.datetime | None = None, extra: str = "", model: str = "") -> str:
    now = now or datetime.datetime.now()
    engine = f" Right now your answers are generated by the model {model}." if model else ""
    parts = [
        soul.persona(name),
        f"- About yourself: Lanterna is a free, open-source app created by {AUTHOR} ({HOMEPAGE}). "
        f"If asked who made you, say that Lanterna was made by {AUTHOR}.{engine}",
        f"\nNow: {now:%A, %d %B %Y, %H:%M} (user's local time).",
        "Formatting: plain text or light Markdown. Use code blocks only for code.",
    ]
    if extra:
        parts.append(extra)
    return "\n".join(parts)


@dataclass
class Conversation:
    router: Router
    user_name: str = ""
    history: list[dict] = field(default_factory=list)
    last_reply: str = ""

    def _messages(self, text: str) -> list[dict]:
        cur = self.router.current
        sys = system_prompt(self.user_name, extra=soul.mood_hint(text), model=cur.label if cur else "")
        return [{"role": "system", "content": sys}, *self.history[-MAX_HISTORY:], {"role": "user", "content": text}]

    def ask(self, text: str) -> Iterator[str | Switched]:
        """Streams the reply (and Switched notices); the cleaned reply goes to history and self.last_reply."""
        pieces: list[str] = []
        for p in self.router.stream(self._messages(text)):
            if isinstance(p, str):
                pieces.append(p)
            yield p
        reply = soul.humanize("".join(pieces).strip(), self.last_reply)
        self.history += [{"role": "user", "content": text}, {"role": "assistant", "content": reply}]
        self.last_reply = reply
